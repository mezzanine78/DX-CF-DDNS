<#
install.ps1 - one-line installer for DX-CF-DDNS (Cloudflare dynamic DNS for a Windows site).

RMM / N-central (runs as SYSTEM; values come from per-client RMM variables, the token from a secure one):
  $env:CF_DDNS_TOKEN='<secure var>'; $env:CF_ZONE_ID='<zone id>'; $env:CF_DDNS_RECORD='site1.example.com'
  irm https://raw.githubusercontent.com/mezzanine78/DX-CF-DDNS/main/install.ps1 | iex
Technician (elevated PowerShell; leave CF_DDNS_TOKEN empty to be prompted, input hidden):
  $env:CF_ZONE_ID='<zone id>'; $env:CF_DDNS_RECORD='site1.example.com'; irm <url>/install.ps1 | iex
Uninstall:
  $env:CF_DDNS_UNINSTALL='1'; irm <url>/install.ps1 | iex

Inputs (environment variables; no param() block so it works through iex). Anything not given on a re-run keeps the
value already in the config (so a re-run without CF_DDNS_TOKEN keeps the stored token):
  CF_DDNS_TOKEN       Cloudflare API token, Zone > DNS > Edit on this zone only (required on first install)
  CF_ZONE_ID          32-hex zone ID (required on first install)
  CF_DDNS_RECORD      one or more FQDNs, separated by , or ; (required on first install)
  CF_DDNS_INTERVAL    minutes between runs, default 5, 1-1440
  CF_DDNS_PROXIED     true/false. Used when creating (default false); an existing record's proxy flag is only
                      changed when this is set
  CF_DDNS_TTL         1 (auto, default when creating) or 60-86400; an existing record's TTL only changes when set
  CF_DDNS_CREATE      1 = create a missing record (default off: a typo cannot create junk records)
  CF_DDNS_IPV6        1 = also keep AAAA records on the public IPv6 (default off)
  CF_DDNS_NTFY_URL    ntfy topic URL for IP-change / failure alerts (throttled); 'none' clears it
  CF_DDNS_NTFY_TOKEN  ntfy bearer token; 'none' clears it
  CF_DDNS_UNINSTALL=1 remove the task and our files (logs are kept)
  CF_DDNS_NORUNNOW=1  do not run the updater once after installing
  CF_DDNS_SKIPVERIFY=1 skip the Cloudflare token / zone check at install
  CF_DDNS_ROOTDIR     default C:\Windows\Scripts\DX (shared with DX-CFTrustedIPs; only DX-CF-DDNS.* files are ours)
  CF_DDNS_REPOURL     raw base URL, default https://raw.githubusercontent.com/mezzanine78/DX-CF-DDNS/main
                      (point it at a commit for an immutable release; the pin below must match it)

Downloads src/DX-CF-DDNS.ps1 over TLS 1.2 (1.3 on build 20348+), checks the SHA256 pinned below (tools/Update-Pins.ps1)
and that it parses, verifies the token (/user/tokens/verify) and its DNS access to the zone, then installs:
  <root>\Scripts\DX-CF-DDNS.ps1, <root>\Config\DX-CF-DDNS.json (SYSTEM + Administrators only, by SID),
  <root>\State\DX-CF-DDNS-state.json, <root>\Logs\DX-CF-DDNS.log, task \DX\DX-CF-DDNS (SYSTEM, every N min + startup).

Exit codes / $LASTEXITCODE:
  0 = installed (first run OK) / uninstalled
  1 = bad or missing input, not Windows, install error
  2 = not elevated
  3 = download failed, SHA256 mismatch or the script does not parse
  4 = installed, but the first run failed (task stays registered; see the log)
  5 = Cloudflare rejected the token, or it has no DNS access to the zone / wrong zone ID
Never calls exit in an interactive console (sets $global:LASTEXITCODE instead). No secrets in this file.
#>
& {
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'
    $DefaultRepoUrl = 'https://raw.githubusercontent.com/mezzanine78/DX-CF-DDNS/main'
    # BEGIN-PINS (generated by tools/Update-Pins.ps1 - SHA256 of the files at this release)
    $Pins = @{
        'src/DX-CF-DDNS.ps1' = '7A1F04D54D5512A1159EB66F68C8DA448D0FF97C4C76B85D92332AB5B124A5DF'
    }
    # END-PINS
    $TaskPath = '\DX\'
    $TaskName = 'DX-CF-DDNS'
    $Marker = 'DX Cloudflare DDNS updater'
    $Api = 'https://api.cloudflare.com/client/v4'

    # OS-specific actions as scriptblocks: the tests swap them via $global:CfDdnsOpsOverride. Nothing in production sets it.
    $Ops = @{
        IsWindows      = { $env:OS -eq 'Windows_NT' }
        IsElevated     = {
            $p = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
            $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
        }
        CanPrompt      = {
            $id = $null
            if ($env:OS -eq 'Windows_NT') { $id = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value }
            [Environment]::UserInteractive -and $id -ne 'S-1-5-18' -and
            -not ([Environment]::GetCommandLineArgs() -match '^-(noni|noninteractive)$')
        }
        ReadToken      = { Read-Host -Prompt 'Cloudflare API token for DX-CF-DDNS (input hidden)' -AsSecureString }
        ProtectPath    = {
            param([string]$Path, [bool]$Directory)
            # SYSTEM (S-1-5-18) + Administrators (S-1-5-32-544) full control, inheritance removed. SIDs, not names.
            $acl = Get-Acl -LiteralPath $Path
            $acl.SetAccessRuleProtection($true, $false)
            foreach ($r in @($acl.Access)) { [void]$acl.RemoveAccessRule($r) }
            $inherit = [System.Security.AccessControl.InheritanceFlags]::None
            if ($Directory) { $inherit = [System.Security.AccessControl.InheritanceFlags]'ContainerInherit, ObjectInherit' }
            foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
                $id = New-Object System.Security.Principal.SecurityIdentifier($sid)
                $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($id, 'FullControl', $inherit,
                                [System.Security.AccessControl.PropagationFlags]::None, 'Allow')))
            }
            Set-Acl -LiteralPath $Path -AclObject $acl
        }
        RegisterTask   = {
            param([string]$Arguments, [int]$Minutes)
            $psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
            $action = New-ScheduledTaskAction -Execute $psExe -Argument $Arguments
            $start = (Get-Date).AddMinutes(1)
            if ([Environment]::OSVersion.Version.Build -lt 10240) {
                # Windows 8.1 / 2012 R2: no duration means "1 day" or a registration error there
                $every = New-ScheduledTaskTrigger -Once -At $start -RepetitionInterval (New-TimeSpan -Minutes $Minutes) -RepetitionDuration ([TimeSpan]::FromDays(3650))
            }
            else { $every = New-ScheduledTaskTrigger -Once -At $start -RepetitionInterval (New-TimeSpan -Minutes $Minutes) }
            $boot = New-ScheduledTaskTrigger -AtStartup
            $boot.Delay = 'PT1M'
            $principal = New-ScheduledTaskPrincipal -UserId 'S-1-5-18' -LogonType ServiceAccount -RunLevel Highest
            $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
                -ExecutionTimeLimit (New-TimeSpan -Minutes 10) -MultipleInstances IgnoreNew
            Register-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Action $action -Trigger @($every, $boot) `
                -Principal $principal -Settings $settings -Force `
                -Description 'DX: keep this site''s Cloudflare DNS record(s) on its public IP (DX-CF-DDNS)' | Out-Null
        }
        UnregisterTask = {
            if (Get-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction SilentlyContinue) {
                Unregister-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Confirm:$false
                return $true
            }
            return $false
        }
        RunScript      = {
            param([string]$Arguments)
            # Windows PowerShell 5.1 child, exactly as the task runs it; it reads the token from the ACL'd config.
            $psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
            $p = Start-Process -FilePath $psExe -ArgumentList "$Arguments -Force" -Wait -PassThru -NoNewWindow
            return $p.ExitCode
        }
        Exit           = {
            param([int]$Code)
            # Only end the process when nobody is sitting at it (RMM, SYSTEM, -Command / -File / -NonInteractive).
            if (-not [Environment]::UserInteractive -or
                ([Environment]::GetCommandLineArgs() -match '^-(c|command|noni|noninteractive|file|f|encodedcommand|e|ec)$')) {
                exit $Code
            }
        }
    }
    $override = Get-Variable -Name CfDdnsOpsOverride -Scope Global -ValueOnly -ErrorAction SilentlyContinue
    if ($override -is [hashtable]) { foreach ($k in @($override.Keys)) { $Ops[$k] = $override[$k] } }

    function Write-DXLine([string]$Msg, [string]$Level = 'INFO') {
        Write-Host ('{0} DX cf-ddns-install {1,-5} {2}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Msg)
    }

    function Get-DXEnv([string]$Name) {
        $v = [Environment]::GetEnvironmentVariable($Name)
        if ($null -eq $v) { return '' }
        return $v.Trim()
    }

    function ConvertTo-DXBool([string]$Value, [string]$Name) {
        # '' -> $null (not given); throws on anything that is not a recognisable yes/no
        if ($Value -eq '') { return $null }
        if ($Value -match '^(1|true|yes|on)$') { return $true }
        if ($Value -match '^(0|false|no|off)$') { return $false }
        throw "$Name must be true/false (or 1/0)"
    }

    function Get-DXTlsProtocolSet([int]$Current, [int]$Build, [bool]$IsWin, [string[]]$Names) {
        $p = $Current -bor 3072                                                       # Tls12
        if ($Names -contains 'Tls13' -and (-not $IsWin -or $Build -ge 20348)) { $p = $p -bor 12288 }  # Tls13
        return $p
    }

    function Test-DXTlsFailure($Exception) {
        $e = $Exception; $n = 0
        while ($null -ne $e -and $n -lt 10) {
            if ($e -is [Net.WebException] -and $e.Status -eq [Net.WebExceptionStatus]::SecureChannelFailure) { return $true }
            if ($e -is [Security.Authentication.AuthenticationException]) { return $true }
            if ([string]$e.Message -match 'SSL/TLS|secure channel|SSL connection could not be established|TLS handshake') { return $true }
            $e = $e.InnerException; $n++
        }
        return $false
    }

    function Write-DXTlsHint {
        $build = [Environment]::OSVersion.Version.Build
        Write-DXLine "TLS handshake failed (Windows build $build, PowerShell $($PSVersionTable.PSVersion)). Set DWORD SchUseStrongCrypto=1 and SystemDefaultTlsVersions=1 under HKLM:\SOFTWARE\Microsoft\.NETFramework\v4.0.30319 and HKLM:\SOFTWARE\WOW6432Node\Microsoft\.NETFramework\v4.0.30319, then re-run." 'ERROR'
        if ($build -eq 9600) { Write-DXLine 'Windows 8.1 / Server 2012 R2: install the TLS 1.2 rollup updates (KB3140245 era and later); Cloudflare needs TLS 1.2 with ECDHE-GCM cipher suites.' 'ERROR' }
    }

    function Get-DXPath([string]$Root) {
        $o = [ordered]@{ Root = $Root; Scripts = (Join-Path $Root 'Scripts'); Config = (Join-Path $Root 'Config')
            State = (Join-Path $Root 'State'); Logs = (Join-Path $Root 'Logs') }
        $o.Script = Join-Path $o.Scripts 'DX-CF-DDNS.ps1'
        $o.ConfigFile = Join-Path $o.Config 'DX-CF-DDNS.json'
        $o.StateFile = Join-Path $o.State 'DX-CF-DDNS-state.json'
        $o.LogFile = Join-Path $o.Logs 'DX-CF-DDNS.log'
        return [pscustomobject]$o
    }

    function Get-DXRemoteScript([string]$BaseUrl, [string]$RelPath) {
        $tmp = [IO.Path]::GetTempFileName()
        try {
            Invoke-WebRequest -Uri "$BaseUrl/$RelPath" -UseBasicParsing -TimeoutSec 60 -OutFile $tmp
            $hash = (Get-FileHash -LiteralPath $tmp -Algorithm SHA256).Hash
            $pin = [string]$Pins[$RelPath]
            if (-not $pin -or $hash -ne $pin.ToUpperInvariant()) { throw "SHA256 mismatch for $RelPath (got $hash, pinned $pin)" }
            Write-DXLine "$RelPath SHA256 OK"
            $bytes = [IO.File]::ReadAllBytes($tmp)
            $text = [Text.Encoding]::UTF8.GetString($bytes)
            $errors = $null
            [void][Management.Automation.Language.Parser]::ParseInput($text, [ref]$null, [ref]$errors)
            if (@($errors).Count) { throw "$RelPath does not parse: $($errors[0].Message)" }
            if (-not $text.Contains($Marker)) { throw "$RelPath is not the expected file" }
            return , $bytes
        }
        finally { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
    }

    function Invoke-DXCf([string]$Token, [string]$Path) {
        # GET against the Cloudflare API. Returns Ok / Status / Result / Codes / Message; never throws, never logs the token.
        try {
            $r = Invoke-RestMethod -Uri ($Api + $Path) -Method Get -UseBasicParsing -TimeoutSec 30 `
                -Headers @{ Authorization = "Bearer $Token"; 'User-Agent' = 'dx-cf-ddns-install/1.0' }
            return [pscustomobject]@{ Ok = [bool]$r.success; Status = 200; Result = $r.result; Codes = @($r.errors | ForEach-Object { $_.code }); Message = '' }
        }
        catch {
            $status = 0
            try { if ($null -ne $_.Exception.Response) { $status = [int]$_.Exception.Response.StatusCode } } catch { $status = 0 }
            $codes = @(); $msg = $_.Exception.Message
            if ($_.ErrorDetails -and $_.ErrorDetails.Message) {
                try { $j = $_.ErrorDetails.Message | ConvertFrom-Json; $codes = @($j.errors | ForEach-Object { $_.code })
                    $msg = (@($j.errors) | ForEach-Object { "$($_.code): $($_.message)" }) -join '; ' } catch { $null = $_ }
            }
            if (-not $status -and (Test-DXTlsFailure $_.Exception)) { Write-DXTlsHint }
            return [pscustomobject]@{ Ok = $false; Status = $status; Result = $null; Codes = $codes; Message = $msg }
        }
    }

    function Test-DXCloudflareAccess([string]$Token, [string]$Zone, [string[]]$Records, [bool]$Create) {
        # 0 = usable; 5 = token rejected / no access to this zone / wrong zone ID. Messages never contain the token.
        $v = Invoke-DXCf $Token '/user/tokens/verify'
        $verified = $v.Ok -and [string]$v.Result.status -eq 'active'
        if ($verified) { Write-DXLine 'API token verified (active)' }
        elseif ($v.Ok) { Write-DXLine "API token is not active (status '$($v.Result.status)'): it expired or was disabled; create a new one" 'ERROR'; return 5 }
        $z = Invoke-DXCf $Token "/zones/$Zone/dns_records?per_page=1"
        if (-not $z.Ok) {
            if ($v.Status -eq 401 -or ($v.Codes -contains 1000) -or $z.Status -eq 401) {
                Write-DXLine 'Cloudflare rejected the API token (401 / invalid token): wrong, revoked or expired. Create a new one (Zone > DNS > Edit) and update CF_DDNS_TOKEN.' 'ERROR'
            }
            elseif ($z.Status -eq 403) {
                Write-DXLine "the token has no DNS access to zone $Zone (HTTP 403): edit the token to Zone > DNS > Edit, Include > Specific zone > this zone, or check CF_ZONE_ID." 'ERROR'
            }
            elseif ($z.Status -eq 400 -or $z.Status -eq 404 -or ($z.Codes -contains 7003) -or ($z.Codes -contains 7000)) {
                Write-DXLine "zone $Zone was not found (HTTP $($z.Status)): check CF_ZONE_ID (zone Overview > API > Zone ID)." 'ERROR'
            }
            else { Write-DXLine "could not check the zone: $($z.Message)" 'ERROR' }
            return 5
        }
        if (-not $verified) { Write-DXLine 'token verify endpoint did not confirm the token (account-owned token?), but it can read the zone''s DNS: OK' 'WARN' }
        Write-DXLine "token can read DNS in zone $Zone"
        foreach ($n in $Records) {
            $r = Invoke-DXCf $Token "/zones/$Zone/dns_records?type=A&name=$([uri]::EscapeDataString($n))"
            if ($r.Ok -and @($r.Result | Where-Object { $_ }).Count -eq 0) {
                if ($Create) { Write-DXLine "A record $n does not exist yet: it will be created (CF_DDNS_CREATE=1)" }
                else { Write-DXLine "A record $n does not exist: create it in the dashboard or set CF_DDNS_CREATE=1 (the updater exits 5 until then)" 'WARN' }
            }
        }
        return 0
    }

    function Write-DXOwnedFile([string]$Path, [byte[]]$Bytes) {
        # Create empty -> restrict -> write, so the content (token) is never readable through an inherited ACL.
        if (-not (Test-Path -LiteralPath $Path)) { [IO.File]::WriteAllBytes($Path, [byte[]]@()) }
        & $Ops.ProtectPath $Path $false
        [IO.File]::WriteAllBytes($Path, $Bytes)
    }

    function Invoke-DXUninstall([string]$Root) {
        $p = Get-DXPath $Root
        if (& $Ops.UnregisterTask) { Write-DXLine "removed task $TaskPath$TaskName" }
        foreach ($f in @($p.Script, $p.ConfigFile, $p.StateFile)) {
            if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force; Write-DXLine "removed $f" }
        }
        # Folders are shared with other DX tools: removed only when empty.
        foreach ($d in @($p.Scripts, $p.Config, $p.State, $p.Root)) {
            if ((Test-Path -LiteralPath $d) -and @(Get-ChildItem -LiteralPath $d -Force).Count -eq 0) {
                Remove-Item -LiteralPath $d -Force; Write-DXLine "removed empty folder $d"
            }
        }
        Write-DXLine "uninstalled (log kept: $($p.LogFile))"
        return 0
    }

    $rc = 1
    $msg = 'failed'
    $token = $null
    try {
        try {
            $isWinOs = ($env:OS -eq 'Windows_NT'); $build = 0
            if ($isWinOs) { $build = [Environment]::OSVersion.Version.Build }
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType](Get-DXTlsProtocolSet -Current ([int][Net.ServicePointManager]::SecurityProtocol) -Build $build -IsWin $isWinOs -Names ([enum]::GetNames([Net.SecurityProtocolType])))
        }
        catch { $null = $_ }

        if (-not (& $Ops.IsWindows)) { $rc = 1; $msg = 'Windows only'; throw [InvalidOperationException]'input' }
        if (-not (& $Ops.IsElevated)) {
            Write-DXLine 'This needs an elevated PowerShell (Administrator) or SYSTEM: Start > PowerShell > right-click > Run as administrator, then run the one-liner again.' 'ERROR'
            $rc = 2; $msg = 'not elevated'; throw [InvalidOperationException]'input'
        }
        $root = Get-DXEnv 'CF_DDNS_ROOTDIR'
        if (-not $root) {
            $sr = [string]$env:SystemRoot
            if (-not $sr) { $sr = 'C:\Windows' }
            $root = $sr.TrimEnd('\', '/') + '\Scripts\DX'
        }
        $p = Get-DXPath $root
        if ((Get-DXEnv 'CF_DDNS_UNINSTALL') -match '^(1|true|yes|on)$') {
            $rc = Invoke-DXUninstall $root; $msg = 'uninstall finished'; throw [InvalidOperationException]'done'
        }

        # ---- inputs: env var > existing config > default
        $old = $null
        if (Test-Path -LiteralPath $p.ConfigFile) {
            try { $old = Get-Content -LiteralPath $p.ConfigFile -Raw | ConvertFrom-Json; Write-DXLine "existing config found: values not given are kept" }
            catch { Write-DXLine 'existing config is not valid JSON; ignoring it' 'WARN' }
        }
        $pick = { param($EnvName, $OldValue) $e = Get-DXEnv $EnvName; if ($e -ne '') { return $e }; return $OldValue }
        $zone = ([string](& $pick 'CF_ZONE_ID' $old.ZoneId)).Trim().ToLowerInvariant()
        if ($zone -notmatch '^[0-9a-f]{32}$') { $rc = 1; $msg = 'set $env:CF_ZONE_ID to the 32-hex zone ID (zone Overview > API > Zone ID)'; throw [InvalidOperationException]'input' }
        $recRaw = Get-DXEnv 'CF_DDNS_RECORD'
        $records = @()
        if ($recRaw) { $records = @($recRaw -split '[,;\s]+') } elseif ($old) { $records = @($old.Records) }
        $records = @($records | Where-Object { $_ } | ForEach-Object { ([string]$_).Trim().TrimEnd('.').ToLowerInvariant() } | Select-Object -Unique)
        if ($records.Count -eq 0) { $rc = 1; $msg = 'set $env:CF_DDNS_RECORD to the FQDN(s) to update, e.g. site1.example.com'; throw [InvalidOperationException]'input' }
        foreach ($n in $records) {
            if ($n -notmatch '^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$') { $rc = 1; $msg = "CF_DDNS_RECORD: '$n' is not a valid FQDN"; throw [InvalidOperationException]'input' }
        }
        $interval = 5
        $iv = [string](& $pick 'CF_DDNS_INTERVAL' $old.IntervalMinutes)
        if ($iv -and (-not [int]::TryParse($iv, [ref]$interval) -or $interval -lt 1 -or $interval -gt 1440)) { $rc = 1; $msg = 'CF_DDNS_INTERVAL must be whole minutes, 1-1440'; throw [InvalidOperationException]'input' }
        try {
            $proxied = ConvertTo-DXBool (Get-DXEnv 'CF_DDNS_PROXIED') 'CF_DDNS_PROXIED'
            if ($null -eq $proxied -and $old -and $null -ne $old.Proxied) { $proxied = [bool]$old.Proxied }
            $create = ConvertTo-DXBool (Get-DXEnv 'CF_DDNS_CREATE') 'CF_DDNS_CREATE'
            if ($null -eq $create) { $create = [bool]$old.Create }
            $ipv6 = ConvertTo-DXBool (Get-DXEnv 'CF_DDNS_IPV6') 'CF_DDNS_IPV6'
            if ($null -eq $ipv6) { $ipv6 = [bool]$old.IPv6 }
        }
        catch { $rc = 1; $msg = $_.Exception.Message; throw [InvalidOperationException]'input' }
        $ttl = $null
        $tv = [string](& $pick 'CF_DDNS_TTL' $old.Ttl)
        if ($tv) {
            $t = 0
            if (-not [int]::TryParse($tv, [ref]$t) -or ($t -ne 1 -and ($t -lt 60 -or $t -gt 86400))) { $rc = 1; $msg = 'CF_DDNS_TTL must be 1 (auto) or 60-86400'; throw [InvalidOperationException]'input' }
            $ttl = $t
        }
        $ntfyUrl = [string](& $pick 'CF_DDNS_NTFY_URL' $old.NtfyUrl)
        if ($ntfyUrl -eq 'none') { $ntfyUrl = '' }
        if ($ntfyUrl -and $ntfyUrl -notmatch '^https://[^\s/]+/') { $rc = 1; $msg = 'CF_DDNS_NTFY_URL must be https://<host>/<topic> (or none)'; throw [InvalidOperationException]'input' }
        $ntfyToken = [string](& $pick 'CF_DDNS_NTFY_TOKEN' $old.NtfyToken)
        if ($ntfyToken -eq 'none') { $ntfyToken = '' }

        $token = Get-DXEnv 'CF_DDNS_TOKEN'
        if (-not $token -and $old -and [string]$old.Token) { $token = [string]$old.Token; Write-DXLine 'CF_DDNS_TOKEN not given: keeping the token from the existing config' }
        if (-not $token) {
            if (-not (& $Ops.CanPrompt)) { $rc = 1; $msg = 'CF_DDNS_TOKEN is empty and this session cannot prompt (set it from a secure RMM variable)'; throw [InvalidOperationException]'input' }
            $secure = & $Ops.ReadToken
            if ($secure -is [Security.SecureString] -and $secure.Length -gt 0) {
                $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
                try { $token = ([Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)).Trim() }
                finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr); $secure.Dispose(); $secure = $null }
            }
            if (-not $token) { $rc = 1; $msg = 'no token entered'; throw [InvalidOperationException]'input' }
        }
        if ($token -notmatch '^[A-Za-z0-9_-]{20,200}$') { $rc = 1; $msg = 'CF_DDNS_TOKEN does not look like a Cloudflare API token'; throw [InvalidOperationException]'input' }

        # ---- download (pinned) + verify against Cloudflare
        $repo = (& $pick 'CF_DDNS_REPOURL' $DefaultRepoUrl).TrimEnd('/')
        if ($repo -notmatch '^https://[^\s/]+/' -and $repo -notmatch '^http://(127\.0\.0\.1|localhost)(:\d+)?(/|$)') { $rc = 1; $msg = 'CF_DDNS_REPOURL must be an https:// URL'; throw [InvalidOperationException]'input' }
        try { $scriptBytes = Get-DXRemoteScript -BaseUrl $repo -RelPath 'src/DX-CF-DDNS.ps1' }
        catch {
            if (Test-DXTlsFailure $_.Exception) { Write-DXTlsHint }
            $rc = 3; $msg = "could not get the updater script: $($_.Exception.Message)"; throw [InvalidOperationException]'input'
        }
        if ((Get-DXEnv 'CF_DDNS_SKIPVERIFY') -match '^(1|true|yes|on)$') { Write-DXLine 'CF_DDNS_SKIPVERIFY=1: token / zone check skipped' 'WARN' }
        else {
            $v = Test-DXCloudflareAccess -Token $token -Zone $zone -Records $records -Create $create
            if ($v -ne 0) { $rc = $v; $msg = 'Cloudflare token / zone check failed, nothing installed'; throw [InvalidOperationException]'input' }
        }

        # ---- folders: create missing ones restricted; existing (shared) folders keep their ACL
        $parent = Split-Path -Parent $p.Root
        if ($parent -and -not (Test-Path -LiteralPath $parent)) { New-Item -ItemType Directory -Path $parent -Force | Out-Null; Write-DXLine "created $parent" }
        foreach ($d in @($p.Root, $p.Scripts, $p.Config, $p.State, $p.Logs)) {
            if (Test-Path -LiteralPath $d) { Write-DXLine "$d exists (shared DX folder): its ACL is left as is" 'DEBUG' }
            else {
                New-Item -ItemType Directory -Path $d -Force | Out-Null
                & $Ops.ProtectPath $d $true
                Write-DXLine "created $d (SYSTEM + Administrators only)"
            }
        }
        Write-DXOwnedFile $p.Script $scriptBytes
        Write-DXLine "updater -> $($p.Script)"
        $cfg = [ordered]@{ ZoneId = $zone; Records = $records; Token = $token; Proxied = $proxied; Ttl = $ttl; Create = $create
            IPv6 = $ipv6; IntervalMinutes = $interval; NtfyUrl = $ntfyUrl; NtfyToken = $ntfyToken }
        Write-DXOwnedFile $p.ConfigFile ((New-Object Text.UTF8Encoding($false)).GetBytes(($cfg | ConvertTo-Json)))
        $cfg = $null
        Write-DXLine "config -> $($p.ConfigFile) (SYSTEM + Administrators only): zone $zone, records $($records -join ', '), every $interval min, proxied=$proxied, ttl=$ttl, create=$create, ipv6=$ipv6, ntfy=$([bool]$ntfyUrl)"
        if (Test-Path -LiteralPath $p.StateFile) { & $Ops.ProtectPath $p.StateFile $false }
        $taskArgs = "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File `"$($p.Script)`" -ConfigPath `"$($p.ConfigFile)`" " +
        "-StateDir `"$($p.State)`" -LogDir `"$($p.Logs)`""
        & $Ops.RegisterTask $taskArgs $interval
        Write-DXLine "task $TaskPath$TaskName registered (SYSTEM, every $interval min + at startup, 10 min limit, no overlap)"

        if ((Get-DXEnv 'CF_DDNS_NORUNNOW') -match '^(1|true|yes|on)$') { $rc = 0; $msg = 'installed (first run skipped)' }
        else {
            Write-DXLine 'first run...'
            $r = & $Ops.RunScript $taskArgs
            if ($r -ne 0) { $rc = 4; $msg = "installed, but the first run returned $r (see $($p.LogFile))" }
            else { $rc = 0; $msg = "installed; $($records -join ', ') checked" }
        }
    }
    catch {
        if ($_.Exception.Message -notin @('input', 'done') -and $msg -eq 'failed') { $msg = "install error: $($_.Exception.Message)" }
    }
    finally {
        # The tokens are never logged; drop our copies and the env vars, whatever happened.
        $token = $null; $ntfyToken = $null
        Remove-Item Env:CF_DDNS_TOKEN, Env:CF_DDNS_NTFY_TOKEN -ErrorAction SilentlyContinue
    }
    $lvl = 'INFO'
    if ($rc -ne 0) { $lvl = 'ERROR' }
    Write-DXLine "$msg (exit $rc)" $lvl
    $global:LASTEXITCODE = $rc
    & $Ops.Exit $rc
}
